import sharp from 'sharp';
import path from 'path';
import fs from 'fs';

const artifactsDir = 'C:/Users/PC/.gemini/antigravity/brain/b85e6102-b6eb-4565-9493-6e009226675e';
const refPath = path.join(artifactsDir, '.user_uploaded/media_1793903484805_ddd65681.jpg');
const livePath = path.join(artifactsDir, 'luxury_prices_packages_ar_dt.png');
const liveMbPath = path.join(artifactsDir, 'luxury_prices_packages_ar_mb.png');
const outPath = path.join(artifactsDir, 'master_prices_packages_live_comparison.jpg');

async function buildShowcase() {
  console.log('Building side-by-side comparison showcase...');
  const targetH = 1400;

  // Resize Ref
  const refBuf = await sharp(refPath)
    .resize({ height: targetH })
    .toBuffer();
  const refMeta = await sharp(refBuf).metadata();

  // Resize Live Desktop
  const liveBuf = await sharp(livePath)
    .resize({ height: targetH })
    .toBuffer();
  const liveMeta = await sharp(liveBuf).metadata();

  // Resize Live Mobile
  const liveMbBuf = await sharp(liveMbPath)
    .resize({ height: targetH })
    .toBuffer();
  const liveMbMeta = await sharp(liveMbBuf).metadata();

  const totalW = refMeta.width + liveMeta.width + liveMbMeta.width + 40;

  await sharp({
    create: {
      width: totalW,
      height: targetH,
      channels: 3,
      background: '#090D15',
    },
  })
    .composite([
      { input: refBuf, left: 10, top: 0 },
      { input: liveBuf, left: refMeta.width + 20, top: 0 },
      { input: liveMbBuf, left: refMeta.width + liveMeta.width + 30, top: 0 },
    ])
    .jpeg({ quality: 88 })
    .toFile(outPath);

  console.log(`Created master showcase: ${outPath} (${fs.statSync(outPath).size} bytes)`);
}

buildShowcase().catch(console.error);
